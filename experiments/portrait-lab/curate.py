"""Freeze the visually reviewed 24-face selection from two bounded ZIP samples."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parent
SELECTION={
 'p001': {
 5:['glasses','long-dark-hair'],6:['glasses','three-quarter'],11:['headphones','short-hair'],
 12:['long-dark-hair','frontal'],33:['headphones','three-quarter'],44:['uneven-light','dark-hair'],
 56:['red-hair'],57:['three-quarter','dark-background'],58:['freckles','light-hair'],
 64:['three-quarter'],71:['headscarf'],79:['wrinkles','glasses']},
 'p006': {
 5:['moustache','wavy-hair'],18:['wrinkles','dark-skin','cap'],21:['wrinkles','beard','cap'],
 38:['short-dark-hair'],42:['moustache','three-quarter'],47:['beard','red-hair'],
 56:['beard','dark-hair'],59:['uneven-light','facial-hair'],60:['glasses','dark-hair'],
 63:['wrinkles','grey-hair'],64:['uneven-light','three-quarter'],83:['hood','facial-hair']}}

entries=[]
for prefix,selected in SELECTION.items():
    extracted=json.loads((ROOT/'inputs'/f'{prefix}-extracted.json').read_text())
    for i,tags in selected.items():
        entry=extracted[i]
        entry.update(file='inputs/'+entry['file'],tags=tags,acquired='2026-10-19',
            source_url='https://github.com/deepInteligence/25K-synthesized-face',
            license='CC-BY-4.0 (as stated in source README)',
            attribution='Human Faces Dataset Generated by Stable Diffusion, deepintelligence, 2025',
            crop=[0,0,1,1],split='held-out' if i in [58,71,79,60,63,83] else 'exploration')
        entries.append(entry)
(ROOT/'manifest.json').write_text(json.dumps(dict(schema=1,description='24 visually reviewed synthetic adult portraits; two archive fragments, deliberately selected stress cases. Not a demographic benchmark.',portraits=entries),indent=2)+'\n')

parts=[]
for filename,identifier in [('drive-sample.tmp','1xd4k7GLmR6kIC6RRf84AtqZk7hVtH41T'),('drive-sample006.tmp','1FOLxP2Rx8G68Zvsix_bYelpFYrxqzoFz')]:
    path=ROOT/'inputs'/filename
    parts.append(dict(file='inputs/'+filename,drive_id=identifier,range='bytes=0-33554431',sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
(ROOT/'acquisition.json').write_text(json.dumps(dict(source='https://github.com/deepInteligence/25K-synthesized-face',folder='https://drive.google.com/drive/folders/1hTfDL2h01fzX7z51GQxB4uaOf8wTbtSU',parts=parts,notes='180 complete CRC-verified PNGs extracted; 24 selected by visual review. Samples are archive-order-biased, not random.'),indent=2)+'\n')
print(f'{len(entries)} selected')
