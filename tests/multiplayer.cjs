'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createFlight,dt} = require('../tools/headless.cjs');
const copy=v=>JSON.parse(JSON.stringify(v));
(async()=>{
 const source=fs.readFileSync(path.join(__dirname,'../experiments/multiplayer-model.js'),'utf8');
 const m=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
 const host=createFlight(),guest=createFlight();
 host.session.prepareMultiplayer(false);guest.session.prepareMultiplayer(true);
 const packet=flight=>({pose:copy(flight.snapshot().state),profile:0,weapon:0,model:'blockout',fire:false,boost:false,rotation:flight.snapshot().asteroid.rotation});
 const h=packet(host),g=packet(guest);
 assert(Math.abs(Math.hypot(...h.pose.eye.map((v,i)=>v-g.pose.eye[i]))*host.DW.sim.METERS_PER_UNIT-90)<1e-8);
 assert(m.pilot(h));assert(m.pilot(g));
 host.session.setRemotePilot(m.pilot(g));guest.session.setRemotePilot(m.pilot(h));
 assert.equal(host.snapshot().combat.enemies.length,1);
 assert.equal(host.snapshot().combat.enemies[0].controller,'input');
 assert.equal(host.snapshot().combat.enabled,false,'co-flight cannot start AI waves or remote damage');
 const start=copy(host.snapshot().state.eye);
 host.advance(1,{throttle:1,fire:true});
 assert.notDeepEqual(copy(host.snapshot().state.eye),start,'production flight advances independently of connection');
 assert(host.snapshot().guns.fired>0,'production weapons still work');
 guest.session.setRemotePilot(m.pilot(packet(host)));
 assert.deepEqual(copy(guest.snapshot().combat.enemies[0].pose.eye),copy(host.snapshot().state.eye));
 const fire={...g,fire:true};host.session.setRemotePilot(fire);host.advance(dt,{stop:true});
 assert(host.snapshot().combat.enemies[0].guns.fired>0,'remote trigger feeds real gun effects');
 const hull=host.snapshot().combat.hull;
 host.advance(2,{stop:true});assert.equal(host.snapshot().combat.hull,hull,'co-flight peer cannot damage local hull');
 host.session.setRemotePilot(null);assert.equal(host.snapshot().combat.enemies.length,0);
 host.advance(1,{throttle:1});assert(!host.snapshot().combat.dead,'disconnect leaves local flight usable');
 host.session.reset({mode:'training',enabled:false,profile:host.config.profile});host.session.prepareMultiplayer(false);
 host.session.setRemotePilot(g);assert.equal(host.snapshot().combat.enemies.length,1,'reset can attach a fresh peer');
 const read=m.receiver(),wire=(seq,pilot=h)=>JSON.stringify({protocol:m.protocol,seq,pilot});
 assert(read.read(wire(2)));assert.equal(read.read(wire(1)),null);assert.equal(read.read(wire(2)),null);
 assert.equal(read.read(wire(3,{...h,pose:{...h.pose,eye:[null,0,0]}})),null);
 assert(read.read(wire(3)),'malformed packets do not consume sequence numbers');
 for(const v of [null,{}, {...h,pose:{...h.pose,right:[0,0,0]}},{...h,pose:{...h.pose,eye:[1e20,0,0]}},{...h,profile:-1},{...h,fire:1}])assert.equal(m.pilot(v),null);
 for(const raw of ['{','null','[]','x'.repeat(8193),JSON.stringify({protocol:'driftworks-arena-v1'})])assert.equal(m.decode(raw),null);
 const filtered=m.pilot({...h,extra:{world:'untrusted'},pose:{...h.pose,curvature:300}});
 assert(!('extra' in filtered));assert(!('curvature' in filtered.pose));
 assert.equal(m.connectionTimeout,20000);
 const autoSource=fs.readFileSync(path.join(__dirname,'../experiments/multiplayer-autopilot.js'),'utf8');
 const {createAutopilot}=await import('data:text/javascript;base64,'+Buffer.from(autoSource).toString('base64'));
 for(const mission of ['default','jade-rime'])for(const isGuest of [false,true]){
  const f=createFlight({mission});f.session.prepareMultiplayer(isGuest);
  const auto=createAutopilot(f.DW);auto.reset(isGuest);const initial=copy(f.snapshot().state);
  const demand=auto.demand(f.snapshot(),dt,f.config.profile,f.config.weapon);
  assert.deepEqual(copy(f.snapshot().state),initial,'AI produces inputs without mutating the pose');
  assert.equal(demand.fire,false);assert.equal(demand.boost,false);
  for(let n=0;n<1200;n++)f.advance(dt,auto.demand(f.snapshot(),dt,f.config.profile,f.config.weapon));
  assert(f.snapshot().state.eye.every(Number.isFinite));
  assert(Math.hypot(...f.snapshot().state.eye.map((v,i)=>v-initial.eye[i]))>.1,'AI flies through real simulation');
  assert.equal(f.snapshot().guns.fired,0,'patrol never fires');
  if(mission==='default')assert(Math.hypot(...f.snapshot().state.eye)>f.snapshot().asteroid.radius*1.12,'patrol stays above asteroid');
 }
 console.log('Multiplayer: real sessions, independent flight, remote pose and weapons, disconnect/reset, packet validation and sequence checks passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
