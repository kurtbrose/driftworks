'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const D={sim:{METERS_PER_UNIT:10000/600}},U=D.sim.METERS_PER_UNIT;
const context=vm.createContext({window:{Driftworks:D},Float32Array,Map,Math,console});
for(const file of ['experiments/retail-weapons.js','experiments/guns.js','assets/ships/aegis-kit/flight-rig.js','src/aegis-sim.js','src/aegis-visual.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:file});
const sim=D.aegisSim.create(),visual=D.aegisVisual.create(sim),state=sim.visualState(),mount=state.mounts[0];
const reference=visual.geometry(),buffers=reference.map(b=>b.vertices);
const pose={eye:[0,0,0],right:[0,1,0],up:[0,0,1],back:[1,0,0]};
D.flightGuns.step(mount.guns,pose,D.retailWeapons[0],true,.01);
D.flightGuns.setVisualOptions({mode:'current',radius:3,exposure:.8,muzzleLight:true,barrelHeat:true});
const lit=visual.geometry(),turret=lit.find(b=>b.gunHeat>0);
assert(turret,'A fired heavy mount emits heat');
assert(Math.abs(turret.gunLights[0]+45.09/U)<1e-5,'Light uses the real heavy muzzle along negative X');
assert(Math.abs(turret.gunLights[1])<1e-5);
assert.equal(turret.gunLights[3],1);
assert(lit.some(b=>b.gunHeat===0&&b.gunLights[3]>0),'Flash also reaches hull batches');
assert(lit.every((b,i)=>b.vertices===buffers[i]),'No hull buffers are rebuilt');
const lightBuffers=lit.map(b=>b.gunLights);
visual.geometry();assert(lit.every((b,i)=>b.gunLights===lightBuffers[i]),'Uniform buffers are reused');
D.flightGuns.step(mount.guns,pose,D.retailWeapons[0],false,.2);
visual.geometry();assert(lit.every(b=>b.gunLights.every(x=>x===0)),'Flash expires while heat remains');
assert(turret.gunHeat>0);
state.parts[0].hp=0;visual.geometry();assert.equal(turret.gunHeat,0,'Destroyed guns cannot glow');
D.flightGuns.setVisualOptions({mode:'current',radius:3,exposure:.8});visual.geometry();
assert(lit.every(b=>!b.gunHeat&&b.gunLights.every(x=>x===0)),'Baseline disables all material effects');
console.log('PASS capital gun effects: authored muzzle, hull spill, independent cooling, destruction, baseline and buffer reuse');
