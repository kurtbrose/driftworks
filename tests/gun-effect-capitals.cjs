'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const D={sim:{METERS_PER_UNIT:10000/600}},U=D.sim.METERS_PER_UNIT;
const context=vm.createContext({window:{Driftworks:D},Float32Array,Map,Math,console});
for(const file of ['experiments/retail-weapons.js','experiments/guns.js','assets/ships/aegis-kit/flight-rig.js','src/aegis-sim.js','src/aegis-visual.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:file});
const sim=D.aegisSim.create(),visual=D.aegisVisual.create(sim),state=sim.visualState(),mount=state.mounts[0];
const reference=visual.geometry(),buffers=reference.map(b=>b.vertices);
const pose={eye:[0,0,0],right:[0,1,0],up:[0,0,1],back:[1,0,0]};
D.flightGuns.step(mount.guns,pose,D.retailWeapons[0],true,.01);
D.flightGuns.setVisualOptions({mode:'current',radius:3,exposure:.8,muzzleLight:true,barrelHeat:true});
const lit=visual.geometry(),turret=lit.find(b=>b.gunHeat>0);
assert(turret,'A fired heavy mount emits heat');
assert(Math.abs(turret.gunLights[0]+45.09/U)<1e-5,'Light uses the real heavy muzzle along negative X');
assert(Math.abs(turret.gunLights[1])<1e-5);
assert.equal(turret.gunLights[3],1);
assert(lit.some(b=>b.gunHeat===0&&b.gunLights[3]>0),'Flash also reaches hull batches');
assert(lit.every((b,i)=>b.vertices===buffers[i]),'No hull buffers are rebuilt');
const lightBuffers=lit.map(b=>b.gunLights);
visual.geometry();assert(lit.every((b,i)=>b.gunLights===lightBuffers[i]),'Uniform buffers are reused');
D.flightGuns.step(mount.guns,pose,D.retailWeapons[0],false,.2);
visual.geometry();assert(lit.every(b=>b.gunLights.every(x=>x===0)),'Flash expires while heat remains');
assert(turret.gunHeat>0);
state.parts[0].hp=0;visual.geometry();assert.equal(turret.gunHeat,0,'Destroyed guns cannot glow');
D.flightGuns.setVisualOptions({mode:'current',radius:3,exposure:.8});visual.geometry();
assert(lit.every(b=>!b.gunHeat&&b.gunLights.every(x=>x===0)),'Baseline disables all material effects');
console.log('PASS capital gun effects: authored muzzle, hull spill, independent cooling, destruction, baseline and buffer reuse');

const receiverState={position:[2,3,1200],heading:Math.PI/2,velocity:[0,0,0],integrity:1000,team:'enemy'};
const receiverOptions={state:receiverState,opponent:{position:[0,0,1200],heading:0,velocity:[0,0,0],integrity:1000,team:'ally'}};
const receiver=D.aegisSim.create(receiverOptions),received=receiver.visualState(),receiverVisual=D.aegisVisual.create(receiver,receiverOptions);
const local=received.mounts[0].source.position;
const point=[receiverState.position[0]-local[1]/U,receiverState.position[1]+local[0]/U,receiverState.position[2]+local[2]/U];
const combat={flashes:[]};
receiver.hit(point.map((v,i)=>v+(i===2?20:0)),point);
assert.equal(received.impactHits.length,0,'Hit/convergence probes do not emit light');
assert.equal(receiver.damage([10000,10000,10000],20,combat),false);
assert.equal(received.impactHits.length,0,'Rejected damage emits no light');
assert(receiver.damage(point,10,combat));assert.equal(received.impactHits.length,0,'Ordinary light rounds do not trigger heavy strike light');
assert(receiver.damage(point,20,combat));assert.equal(received.impactHits.length,1,'Finalized heavy damage records the receiver-local point');
D.flightGuns.setVisualOptions({mode:'current',radius:3,exposure:.8,impactLight:true});
const receiverBatches=receiverVisual.geometry(),hull=receiverBatches[0],light=hull.gunLights;
assert(light[3]>1,'Heavy strike starts with a strong flash');
for(let k=0;k<3;k++)assert(Math.abs(light[k]-local[k]/U)<1e-5,'Rotated receiver transforms the impact to hull-local coordinates');
const frozen=Array.from(light);receiverVisual.geometry();assert.deepEqual(Array.from(light),frozen,'Paused rendering preserves the impact envelope');
receiverState.position[0]+=10;receiverState.heading+=.4;receiverVisual.geometry();
for(let k=0;k<3;k++)assert(Math.abs(light[k]-local[k]/U)<1e-5,'Hull movement and rotation carry the impact light');
received.impactHits[0].time=-.8;receiverVisual.geometry();assert(light.every(x=>x===0),'Impact light expires');
const a=receiverState.heading,newPoint=[receiverState.position[0]+(Math.cos(a)*local[0]-Math.sin(a)*local[1])/U,receiverState.position[1]+(Math.sin(a)*local[0]+Math.cos(a)*local[1])/U,receiverState.position[2]+local[2]/U];
for(let i=0;i<40;i++)assert(receiver.damage(newPoint,20,combat));
assert.equal(receiver.visualState().impactHits.length,32,'The journal is bounded');
receiver.reset();receiverVisual.geometry();assert.equal(receiver.visualState().impactHits.length,0,'Sortie reset clears strike lights');
assert(receiverBatches.every(b=>b.gunLights.every(x=>x===0)));
D.flightGuns.setVisualOptions({mode:'current',radius:3,exposure:.8});
console.log('PASS receiving hull impact light: finalized heavy damage, rejected probes, local placement, motion, pause, expiry and reset');
