'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const {refresh, hash} = require('../tools/refresh-site-assets.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'driftworks-assets-'));
const log = console.log, error = console.error;
try {
  console.log = console.error = () => {};
  for (const dir of ['src', 'assets/backgrounds/features', 'experiments']) fs.mkdirSync(path.join(root, dir), {recursive:true});
  fs.writeFileSync(path.join(root, 'src/app.js'), 'hello\r\n');
  fs.writeFileSync(path.join(root, 'assets/backgrounds/features/sky.png'), Buffer.from([0,13,10,255]));
  const page = path.join(root, 'experiments/test.html');
  fs.writeFileSync(page, '<script src="../src/app.js?mode=demo#start"></script><script type="importmap">{"imports":{"app":"../src/app.js"}}</script><style>body{background:url("../assets/backgrounds/features/sky.png")}</style>');
  assert.ok(refresh(root, true), 'missing helper and versions must fail');
  process.exitCode = 0;
  refresh(root);
  assert.equal(refresh(root, true), 0);
  const html = fs.readFileSync(page, 'utf8');
  assert.match(html, /mode=demo&v=[a-f0-9]{12}#start/);
  assert.match(html, /"app":"\.\.\/src\/app.js\?v=[a-f0-9]{12}"/);
  assert.match(html, /url\("\.\.\/assets\/backgrounds\/features\/sky.png\?v=[a-f0-9]{12}"\)/);
  const context = {window:{}, URL, document:{baseURI:'https://example.test/driftworks/experiments/test.html',currentScript:{getAttribute:()=> '../src/asset-versions.js'}}};
  vm.runInNewContext(fs.readFileSync(path.join(root, 'src/asset-versions.js'),'utf8'), context);
  const asset = context.window.Driftworks.assetUrl('../assets/backgrounds/features/sky.png?quality=2#image');
  assert.match(asset, /\/driftworks\/assets\/backgrounds\/features\/sky.png\?quality=2&v=[a-f0-9]{12}#image$/);
  assert.equal(context.window.Driftworks.assetUrl('https://other.test/a.png'), 'https://other.test/a.png');
  assert.equal(new URL(context.window.Driftworks.assetUrl('features/sky.png', 'https://example.test/driftworks/assets/backgrounds/layout.json?v=old')).searchParams.get('v'), hash(Buffer.from([0,13,10,255]), false));
  assert.equal(hash(Buffer.from('hello\r\n')), hash(Buffer.from('hello\n')), 'text versions survive Git line ending conversion');
  fs.writeFileSync(path.join(root, 'assets/backgrounds/features/sky.png'), 'changed');
  assert.ok(refresh(root, true), 'changed dynamic image invalidates the manifest and HTML');
  process.exitCode = 0;
  refresh(root);
  fs.writeFileSync(page, fs.readFileSync(page,'utf8').replace(/\?mode=demo&v=[a-f0-9]+/, ''));
  assert.ok(refresh(root, true), 'removed version fails');
  process.exitCode = 0;
  refresh(root);
  // A control-only edit updates its callers, without invalidating unrelated pages.
  const unrelated = path.join(root, 'experiments/other.html');
  fs.writeFileSync(unrelated, '<script src="../src/other.js"></script>');
  fs.writeFileSync(path.join(root, 'src/other.js'), 'other');
  fs.mkdirSync(path.join(root, 'assets/ships'), {recursive:true});
  fs.writeFileSync(path.join(root, 'assets/ships/rig.js'), 'rig');
  refresh(root);
  const beforeOther = fs.readFileSync(unrelated, 'utf8');
  const beforeCatalog = fs.readFileSync(path.join(root, 'src/asset-versions.js'), 'utf8');
  const beforePage = fs.readFileSync(page, 'utf8');
  fs.writeFileSync(path.join(root, 'src/app.js'), 'changed controls');
  refresh(root);
  assert.equal(fs.readFileSync(unrelated, 'utf8'), beforeOther);
  assert.equal(fs.readFileSync(path.join(root, 'src/asset-versions.js'), 'utf8'), beforeCatalog);
  assert.notEqual(fs.readFileSync(page, 'utf8'), beforePage);
  assert.ok(beforeCatalog.includes('assets/ships/rig.js'), 'dynamic asset scripts remain versioned');
  assert.ok(!beforeCatalog.includes('src/app.js'), 'ordinary code is versioned by its HTML caller');
  assert.equal(refresh(root, true), 0);
  fs.writeFileSync(path.join(root, 'src/app.js'), "image.src='../assets/backgrounds/features/sky.png';");
  assert.ok(refresh(root, true), 'new dynamic requests must use the URL helper');
  process.exitCode = 0;
  fs.writeFileSync(path.join(root, 'src/app.js'), 'hello\n');
  refresh(root);
  fs.unlinkSync(path.join(root, 'src/app.js'));
  assert.ok(refresh(root, true), 'missing local HTML resource fails');
  process.exitCode = 0;
} finally {
  console.log = log; console.error = error;
  fs.rmSync(root, {recursive:true, force:true});
}
console.log('PASS site asset versions: missing/stale URLs, dynamic images, nested Pages paths and line endings');
