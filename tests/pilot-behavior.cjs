'use strict';
const assert = require('node:assert/strict');
const {run} = require('../tools/pilot-behavior.cjs');
const options = {seconds: 12, count: 8, layout: 'dense', seed: 29};
const a = run(options), b = run(options);
assert.deepEqual(a, b, 'Repeat real AI, stress and channel scheduling exactly');
assert.equal(a.simulatedSeconds, 12);
assert.equal(a.playerDead, false);
assert(a.summary.shots > 0, 'NPCs actually engage');
assert(a.pilots.some(p => p.maxStress > 0), 'Real combat generates stress');
assert(a.timeline.some(s => s.pilots.some(p => p.pursuers > 0)));
assert(a.transcript.length > 0, 'Production radio is scheduled');
assert(a.pilots.every(p => p.meanStress >= 0 && p.meanStress <= 1));
assert.equal(a.summary.helpCalls, a.pilots.reduce((n,p) => n+p.helpCalls,0));
assert.throws(() => run({seconds: NaN}));
assert.throws(() => run({layout: 'typo'}));
const baseline = run({seconds: 120, count: 16, layout: 'dense', seed: 29});
assert(Object.keys(baseline.summary.eventCounts).length >= 6, 'Baseline retains varied radio categories');
assert(baseline.summary.helpFraction < .5, 'Help requests do not dominate this baseline');
assert(baseline.pilots.some(p => p.panickedSeconds > 0), 'Variety is exercised under actual pilot panic');
console.log('PASS pilot behavior: deterministic real AI combat, stress history and radio capture');
