const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const controls = new Map();
for (const id of ['viewer','focus','breadth','depth','spread','wing','embarked','markings','readout','quarter','top','side','reset']) controls.set(id,{value:id==='focus'?'all':id==='wing'?'6':'100',checked:true,clientWidth:900,clientHeight:700});
let batches;
const world={combat:{}};
const scene={setStudyActors(value){batches=value;},setStudyEffects(){},setOrbit(){}};
const context={window:{Driftworks:{sim:{createInitialWorld:()=>world,METERS_PER_UNIT:10},scene3d:{create:()=>scene}}},document:{getElementById:id=>controls.get(id)},requestAnimationFrame(){},Float32Array};
vm.createContext(context);
for(const file of ['src/mesh-builder.js','experiments/fleet-greybox.js']) vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'..',file),'utf8'),context);
const initial=batches.reduce((n,b)=>n+b.vertices.length,0);
assert.ok(initial>0);
assert.ok(batches.every(b=>Array.from(b.vertices).every(Number.isFinite)));
controls.get('embarked').checked=false;controls.get('embarked').oninput();
assert.ok(batches.reduce((n,b)=>n+b.vertices.length,0)<initial,'embarked toggle removes the six fighters');
controls.get('focus').value='fighter';controls.get('focus').onchange();
const before=Array.from(batches[0].vertices);
controls.get('breadth').value='140';controls.get('breadth').oninput();
assert.ok(batches[0].vertices.some((v,i)=>i%6===0 && v!==before[i]),'shared breadth changes hull geometry');
controls.get('reset').onclick();assert.equal(controls.get('breadth').value,'100');
assert.deepEqual(Array.from(batches[0].vertices),before);
console.log('PASS fleet greybox: finite geometry, wing visibility, shared proportions and reset');
