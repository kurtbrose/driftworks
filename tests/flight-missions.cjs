'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={window:{Driftworks:{},location:{search:'?mission=ohio'}}};vm.createContext(context);
for(const file of ['experiments/flight-missions.js','experiments/mission-ohio.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:file});
const api=context.window.Driftworks.flightMissions,defaults=api.resolve(),ohio=api.current();
assert.equal(ohio.id,'ohio');assert.equal(api.resolve('unknown'),defaults);
assert.equal(ohio.units.speedLabel,'mph');assert.equal(ohio.units.distanceLabel,'yd');
assert.equal(ohio.encounter.kind,'furball');assert.equal(ohio.encounter.count,8);
assert.equal(ohio.opening[1].text,'Always has been.');assert.equal(ohio.scenery[0].kind,'highway-sign');
assert.equal(defaults.opening.length,0);assert.equal(defaults.comms.friendlyAddress[0],'pilot');
const patch={units:{distanceLabel:'ft',distanceScale:3.28084},teams:{ally:{target:'TEST'}},opening:[],encounter:{reinforcements:null,callsigns:['Test One']}};
const test=api.define('test',patch,'ohio');
assert.equal(test.units.speedLabel,'mph');assert.equal(test.units.distanceLabel,'ft');
assert.equal(test.teams.ally.status,'Ford Folks');assert.equal(test.teams.ally.target,'TEST');
assert.equal(test.teams.enemy.target,'Chevy Crew');assert.equal(test.opening.length,0);
assert.equal(test.encounter.callsigns.length,1);assert.equal(ohio.encounter.callsigns.length,16);
patch.encounter.callsigns.push('External mutation');assert.equal(test.encounter.callsigns.length,1);
assert(Object.isFrozen(test)&&Object.isFrozen(test.teams.ally));
assert.throws(()=>api.define('test',{}));assert.throws(()=>api.define('bad',{units:{speedScale:0}}));
assert.throws(()=>api.define('missing',{},'nonexistent'));
assert.throws(()=>api.define('unsafe',JSON.parse('{"__proto__":{"polluted":true}}')));
assert.equal(api.address('Pilot, cover {pilot}.',1,false,ohio),'Neighbor, cover {pilot}.');
context.window.location.search='?mission=unknown';assert.equal(api.current(),defaults);
context.window.location.search='?mission=%ZZ';assert.equal(api.current(),defaults);
console.log('PASS mission definitions: inherited defaults, array replacement, immutable snapshots, fallback, Ohio parity and third-mission overrides');

const cinema=api.resolve('cinematic'),jade=api.resolve('gas-giant'),moonSide=api.resolve('jade-rime');
assert.equal(JSON.stringify(cinema.sky.jadeSystem),JSON.stringify(jade.sky.jadeSystem),'cinematic destination uses the close Jade gas-giant observer and frame');
assert.notEqual(JSON.stringify(cinema.sky.jadeSystem.observer),JSON.stringify(moonSide.sky.jadeSystem.observer),'cinematic destination is not the close gray moon view');
assert.equal(cinema.sky.rimeSurface,'','no nearby moon surface is inherited');
assert.equal(cinema.sky.thinShell,true);assert.equal(cinema.sky.wormhole,true);assert.equal(cinema.weaponsDisabled,false);
assert.equal(moonSide.sky.rimeSurface,'jade-moons-v1/rime-disk-v2.png','moon-side free flight remains available');
console.log('PASS cinematic sky: close Jade preset, no inherited close moon surface, thin-shell bridge and combat preserved');
