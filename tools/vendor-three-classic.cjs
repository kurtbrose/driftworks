'use strict';
// Produce a synchronous classic-script distribution from the already vendored r180 modules.
// Only needed when updating the vendored library; deployment has no build step.
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../vendor/three/build');
const object=list=>'{'+list.split(',').map(item=>item.trim().split(' as ')).filter(v=>v[0]).map(v=>v[v.length-1]+':'+v[0]).join(',')+'}';
let core=fs.readFileSync(path.join(root,'three.core.js'),'utf8').replace(/\r\n/g,'\n');
let moduleSource=fs.readFileSync(path.join(root,'three.module.js'),'utf8').replace(/\r\n/g,'\n');
const coreExport=core.match(/export \{([^}]+)\};/);if(!coreExport)throw new Error('Unsupported Three core exports');
core=core.slice(0,coreExport.index)+'return '+object(coreExport[1])+';\n';
moduleSource=moduleSource.replace(/import \{([^}]+)\} from [^;]+;/,(_,names)=>'const {'+names+'}=core;').replace(/export \{[^}]+\} from [^;]+;/g,'');
const moduleExport=moduleSource.match(/export \{([^}]+)\};/);if(!moduleExport)throw new Error('Unsupported Three renderer exports');
moduleSource=moduleSource.slice(0,moduleExport.index)+'return Object.assign({},core,'+object(moduleExport[1])+');\n';
const output='// Three.js r180 classic distribution; generated by tools/vendor-three-classic.cjs. MIT license.\nwindow.THREE=(function(){const core=(function(){\n'+core+'})();\n'+moduleSource+'})();\n';
const file=path.join(root,'three.global.js');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==output)throw new Error('Stale Three.js classic distribution');}
else fs.writeFileSync(file,output);
