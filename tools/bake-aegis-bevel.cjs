'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {pathToFileURL}=require('node:url');
(async()=>{
 const root=path.join(__dirname,'..'),T=await import(pathToFileURL(path.join(root,'vendor/three/build/three.module.js')).href);
 const initial={prow:'lance',count:'6',mission:'standard',drive:'heavy',attachment:'turret',ventral:'turret',explode:'0',preset:'battleship'};
 const elements={};const el=id=>elements[id]||=( {value:initial[id]||'',checked:false,clientWidth:1200,clientHeight:800,addEventListener(t,f){this[t]=f;},prepend(){}});
 class Renderer{setPixelRatio(){}setClearColor(){}setSize(){}setAnimationLoop(){}}
 class Controls{constructor(){this.target=new T.Vector3();}update(){}}
 const ctx=vm.createContext({THREE:{...T,WebGLRenderer:Renderer},OrbitControls:Controls,window:{},devicePixelRatio:1,document:{getElementById:el},ResizeObserver:class{observe(){}}});
 vm.runInContext(fs.readFileSync(path.join(root,'assets/ships/aegis-kit/reference-fighter.js'),'utf8'),ctx);
 const html=fs.readFileSync(path.join(root,'experiments/dreadnaught-kit.html'),'utf8');
 vm.runInContext(html.match(/<script type="module">([\s\S]*?)<\/script>/)[1].replace(/^import .*;$/gm,''),ctx);
 vm.runInContext("el('preset').value='battleship';el('preset').change()",ctx);
 const ship=vm.runInContext('ship',ctx);ship.updateMatrixWorld(true);

 const section=ship.children.find(o=>o.name==='M_1_standard');
 const mesh=section.children.find(o=>o.isMesh&&o.geometry.type==='BufferGeometry'&&o.geometry.attributes.position.count===180);
 if(!mesh)throw new Error('Armor source mesh not found');
 const pos=mesh.geometry.attributes.position,norm=mesh.geometry.attributes.normal,nm=new T.Matrix3().getNormalMatrix(mesh.matrixWorld);
 const bounds=new T.Box3().setFromObject(mesh),center=bounds.getCenter(new T.Vector3()),original=[];
 for(let i=0;i<pos.count;i++){
  const p=new T.Vector3().fromBufferAttribute(pos,i).applyMatrix4(mesh.matrixWorld).sub(center).multiplyScalar(9);
  const n=new T.Vector3().fromBufferAttribute(norm,i).applyMatrix3(nm).normalize();
  original.push(p.x,-p.z,p.y,n.x,-n.z,n.y);
 }
 const candidate=require('./lib/convex-bevel.cjs').bevel(original,.6);
 const data={source:'experiments/dreadnaught-kit.html',sourceHash:require('node:crypto').createHash('sha256').update(html).digest('hex'),section:'M_1_standard / first armor band',centerMeters:[center.x*9,-center.z*9,center.y*9],units:'metres',color:mesh.material.color.toArray(),original,...candidate};
 const text='// Generated by node tools/bake-aegis-bevel.cjs. Review only.\nwindow.AegisBevelData='+JSON.stringify(data,(_,v)=>typeof v==='number'?Number(v.toFixed(7)):v)+';\n';
 const file=path.join(root,'studies/aegis-bevel-data.js');
 if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==text)throw new Error('Bevel data stale');}else fs.writeFileSync(file,text);
 console.log(JSON.stringify({source:data.section,originalTriangles:original.length/18,candidateTriangles:candidate.flat.length/18,faces:candidate.faces,bevelFaces:candidate.bevelFaces,width:candidate.width}));
})().catch(e=>{console.error(e);process.exitCode=1;});
