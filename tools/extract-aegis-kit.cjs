'use strict';
// Reuse the original authoring primitives without evaluating its UI or renderer.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
function generated(){
 const html=fs.readFileSync(path.join(root,'studies/legacy-dreadnaught-kit.html'),'utf8').replace(/\r\n/g,'\n');
 const start=html.indexOf('const mat = '),end=html.indexOf('let segmentOverrides=');
 const attachment=html.slice(html.indexOf('function attach('),html.indexOf('// Shared Spitfire'));
 if(start<0||end<start||!attachment.startsWith('function attach('))throw new Error('Aegis authoring boundaries changed');
 return '// Generated by tools/extract-aegis-kit.cjs from the original authoring study.\nimport * as THREE from \'three\';\n'+html.slice(start,end).replace('let ship;\n','')+attachment+'\nexport {mid,wedge,drive,attach,bridge,box,loft,turret,sensor,connector,hull,armor,pale,dark,trim,gold,blue,amber};\n';
}
function run(check=false){const file=path.join(root,'studies/aegis-module-primitives.js'),source=generated();if(check){if(fs.readFileSync(file,'utf8')!==source)throw new Error('Aegis study primitives are stale');}else fs.writeFileSync(file,source);}
module.exports={generated};if(require.main===module)run(process.argv.includes('--check'));
