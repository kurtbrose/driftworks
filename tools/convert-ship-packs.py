"""Offline OBJ conversion for the isolated flight lab. Python standard library only.
Run from the repository root: python tools/convert-ship-packs.py
Original exports stay untouched. Preview axes: right X, forward Y, up Z;
center each bounding box and fit its furthest vertex into an 8.5 metre sphere.
Legacy OBJ previews omit materials/UVs; Quaternius inspection also imports archived glTF UVs, normals and base-color PNGs.
"""
from pathlib import Path
import hashlib, json, math, base64, struct, zipfile
ROOT=Path(__file__).resolve().parents[1]
PACKS=[('quaternius-ultimate-spaceships','Quaternius','https://quaternius.com/packs/ultimatespaceships.html')]
for key,author,url in PACKS:
 folder=ROOT/'assets/ships'/key
 models=[]
 for path in sorted((folder/'source').rglob('*.obj')):
  points=[];faces=[]
  for line in path.read_text(encoding='utf-8-sig').splitlines():
   fields=line.split()
   if not fields: continue
   if fields[0]=='v':
    x,y,z=map(float,fields[1:4])
    # Quaternius noses point +Z.
    # Rotate Quaternius 180 degrees about up, preserving winding/handedness.
    points.append([-x,z,y])
   elif fields[0]=='f':
    indices=[int(v.split('/')[0]) for v in fields[1:]]
    indices=[i-1 if i>0 else len(points)+i for i in indices]
    faces.extend([indices[0],indices[i],indices[i+1]] for i in range(1,len(indices)-1))
  center=[(min(p[a] for p in points)+max(p[a] for p in points))/2 for a in range(3)]
  points=[[p[a]-center[a] for a in range(3)] for p in points]
  radius=max(math.hypot(*p) for p in points)
  points=[[v*8.5/radius for v in p] for p in points]
  data=[]
  for face in faces:
   a,b,c=[points[i] for i in face];u=[b[i]-a[i] for i in range(3)];v=[c[i]-a[i] for i in range(3)]
   normal=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
   length=math.hypot(*normal)
   if length<1e-10:continue
   normal=[n/length for n in normal]
   for p in (a,b,c):data.extend(round(n,6) for n in p+normal)
  models.append(dict(id=key+':'+path.stem,name=path.stem,source=path.relative_to(folder).as_posix(),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),triangles=len(data)//18,vertices=data))
 # Import the pack's self-contained glTF 2.0 exports offline. Keep the legacy
 # geometry for flight; inspection gets source normals, UVs and base color.
 if key=='quaternius-ultimate-spaceships':
  with zipfile.ZipFile(folder/'source/quaternius_pack.zip') as archive:
   for name in sorted(archive.namelist()):
    if not name.endswith('.gltf'): continue
    doc=json.loads(archive.read(name))
    if doc['asset']['version']!='2.0': raise ValueError('Expected glTF 2.0')
    if len(doc['nodes'])!=1 or set(doc['nodes'][0])-{'mesh','name'}: raise ValueError('Unsupported node transform')
    buffers=[base64.b64decode(b['uri'].split(',',1)[1]) for b in doc['buffers']]
    def accessor(index):
     a=doc['accessors'][index]; view=doc['bufferViews'][a['bufferView']]
     fmt={5126:'f',5123:'H',5125:'I'}[a['componentType']]
     width={'SCALAR':1,'VEC2':2,'VEC3':3}[a['type']]
     size=struct.calcsize('<'+fmt*width); stride=view.get('byteStride',size)
     start=view.get('byteOffset',0)+a.get('byteOffset',0)
     return [struct.unpack_from('<'+fmt*width,buffers[view['buffer']],start+i*stride) for i in range(a['count'])]
    primitive=doc['meshes'][0]['primitives'][0]
    if len(doc['meshes'])!=1 or len(doc['meshes'][0]['primitives'])!=1 or primitive.get('mode',4)!=4: raise ValueError('Expected one triangle primitive')
    attrs=primitive['attributes']; positions=accessor(attrs['POSITION']); normals=accessor(attrs['NORMAL']); uvs=accessor(attrs['TEXCOORD_0'])
    points=[[-x,z,y] for x,y,z in positions]
    center=[(min(p[a] for p in points)+max(p[a] for p in points))/2 for a in range(3)]
    radius=max(math.dist(p,center) for p in points)
    data=[]
    for (i,) in accessor(primitive['indices']):
     x,y,z=normals[i]
     data.extend(round((points[i][a]-center[a])*8.5/radius,6) for a in range(3))
     data.extend([-x,z,y,*uvs[i]])
    model=next(m for m in models if m['name']==Path(name).stem)
    image=doc['images'][0]; view=doc['bufferViews'][image['bufferView']]; start=view.get('byteOffset',0)
    texture=folder/'textures'/ (model['name']+'.png'); texture.parent.mkdir(exist_ok=True)
    texture.write_bytes(buffers[view['buffer']][start:start+view['byteLength']])
    model['texturedVertices']=data
    model['texture']='textures/'+texture.name
    model['gltfSource']=name
 pack=dict(id=key,author=author,url=url,license='CC0-1.0',material='Neutral geometry preview; source materials and textures are not rendered.',models=models)
 (folder/'meshes.js').write_text('// Generated by tools/convert-ship-packs.py; see README.md for provenance.\nwindow.Driftworks.shipPacks = window.Driftworks.shipPacks || [];\nwindow.Driftworks.shipPacks.push('+json.dumps(pack,separators=(',',':'))+');\n',encoding='utf-8',newline='\n')
 print(author,[(m['name'],m['triangles']) for m in models])
