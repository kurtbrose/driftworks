'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),marker='// BEGIN GENERATED HULL INDICES';
function build(vertices,offsets){
 const min=[Infinity,Infinity,Infinity],max=[-Infinity,-Infinity,-Infinity];
 for(const offset of offsets)for(let corner=0;corner<3;corner++)for(let axis=0;axis<3;axis++){const v=vertices[offset+corner*6+axis];min[axis]=Math.min(min[axis],v);max[axis]=Math.max(max[axis],v);}
 if(offsets.length<=12)return {min,max,offsets,left:null,right:null};
 let axis=max[1]-min[1]>max[0]-min[0]?1:0;if(max[2]-min[2]>max[axis]-min[axis])axis=2;
 offsets.sort((a,b)=>vertices[a+axis]+vertices[a+6+axis]+vertices[a+12+axis]-vertices[b+axis]-vertices[b+6+axis]-vertices[b+12+axis]);
 const middle=Math.floor(offsets.length/2);return {min,max,offsets:null,left:build(vertices,offsets.slice(0,middle)),right:build(vertices,offsets.slice(middle))};
}
function bake(rootDirectory=root,check=false){
 const folder=path.join(rootDirectory,'assets/ships');let count=0,bytes=0;
 for(const directory of fs.readdirSync(folder,{withFileTypes:true}).filter(d=>d.isDirectory()).sort((a,b)=>a.name.localeCompare(b.name))){
  const file=path.join(folder,directory.name,'meshes.js');if(!fs.existsSync(file))continue;
  const original=fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n'),source=original.split(marker)[0].trimEnd()+'\n';
  const DW={shipPacks:[]};vm.runInNewContext(source,{window:{Driftworks:DW}},{filename:file});
  const indices={};
  for(const pack of DW.shipPacks)for(const model of pack.models){
   const v=model.vertices;if(!v.length||v.length%18)throw new Error('Invalid triangle mesh '+model.id);
   let radius=0;for(let i=0;i<v.length;i+=6)radius=Math.max(radius,Math.hypot(v[i],v[i+1],v[i+2]));
   indices[model.id]={version:1,vertexCount:v.length,sourceHash:crypto.createHash('sha256').update(JSON.stringify(v)).digest('hex'),radius,tree:build(v,Array.from({length:v.length/18},(_,i)=>i*18))};count++;
  }
  // JavaScript literals retain signed zero in bounds, unlike JSON's numeric encoding.
  const literal=JSON.stringify(indices,(_,value)=>Object.is(value,-0)?'__NEGATIVE_ZERO__':value).replace(/"__NEGATIVE_ZERO__"/g,'-0');
  const suffix=marker+'\n// Generated by tools/bake-hull-indices.cjs; source mesh bytes above are unchanged.\n(function(){var data='+literal+';var packs=window.Driftworks.shipPacks;var pack=packs[packs.length-1];pack.models.forEach(function(model){model.hullIndex=data[model.id];});}());\n';
  const next=source+suffix;bytes+=Buffer.byteLength(suffix);
  if(check){if(original!==next)throw new Error('Stale hull indices: '+path.relative(rootDirectory,file)+'; run node tools/bake-hull-indices.cjs');}
  else if(original!==next)fs.writeFileSync(file,next,'utf8');
 }
 return {models:count,addedBytes:bytes};
}
if(require.main===module){const result=bake(root,process.argv.includes('--check'));console.log('Hull indices '+(process.argv.includes('--check')?'match':'baked')+': '+result.models+' models, '+result.addedBytes+' generated bytes.');}
module.exports={bake,build,marker};
